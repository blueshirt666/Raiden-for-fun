# 验证两个恒等式：K_task == 参考门数，C_ref == 参考门数 * 参考深度^3
rows = [
 ("#1 AND",2,2,16),("#4 NAND",1,1,1),("#23 8-3优先编码",44,14,120736),
 ("#29 4位相等",26,8,13312),("#37 4位加(无cin)",32,10,32000),
 ("#48 8位popcount",71,16,290816),("#42 4位加减",344,19,2359496),
 ("#61 8x8乘",600,68,188659200),("#72 4位饱和加",258,16,1056768),
 ("#73 T触发器",5,3,297),("#253 4位平均",229,17,1125077),
 ("#255 4位条件交换",257,17,1262641),("#256 两位BCD转二进制",189,15,637875),
 ("#259 8位高低字节相等",111,17,545343),("#260 4位与8位拼接进位加",938,25,14656250),
]
bad=0
for name,K,d,Cref in rows:
    calc = K*max(d,1)**3
    ok = (calc==Cref)
    if not ok: bad+=1
    print(f"{name:26s} K={K:4d} d={d:3d}  n*d^3={calc:>11,}  C_ref={Cref:>11,}  {'OK' if ok else 'MISMATCH'}")
print("\nmismatches:",bad)
